"""CMMS MCP server: the external system-of-record boundary.

Run standalone (stdio):
    python -m mcp_server.cmms_server
"""

from __future__ import annotations

import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from uuid import uuid4

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from mcp.server.fastmcp import FastMCP

from fieldops.db import approve_draft, create_draft, get_by_work_order_id, get_draft, init_db

mcp = FastMCP("cmms", host="127.0.0.1", port=8765)


@mcp.tool()
def create_work_order(
    draft_id: str,
    asset_id: str,
    title: str,
    description: str,
    priority: str = "P2",
    parts: list[str] | None = None,
    scheduled_at: str | None = None,
) -> dict:
    """Create a work order in CMMS from an approved draft.

    Args:
        draft_id: Draft ID generated by the local draft tool.
        asset_id: Device serial number.
        title: Work order title.
        description: Symptom, diagnosis and recommended action.
        priority: P1 / P2 / P3.
        parts: Part numbers to bring.
        scheduled_at: Suggested visit time.
    """

    init_db()
    draft = get_draft(draft_id)
    if draft is None:
        draft = create_draft(
            draft_id=draft_id,
            asset_id=asset_id,
            title=title,
            description=description,
            priority=priority,
            parts=parts or [],
            safety=["执行 LOTO 断电并确认零能量"],
            scheduled_at=scheduled_at,
        )

    if draft["status"] == "approved" and draft.get("work_order_id"):
        return {
            "work_order_id": draft["work_order_id"],
            "draft_id": draft_id,
            "status": "already_approved",
        }

    work_order_id = f"WO-{datetime.now(timezone.utc):%Y%m%d}-{uuid4().hex[:4].upper()}"
    approve_draft(draft_id, work_order_id)
    return {
        "work_order_id": work_order_id,
        "draft_id": draft_id,
        "asset_id": asset_id,
        "title": title,
        "priority": priority,
        "scheduled_at": scheduled_at,
        "status": "approved",
    }


@mcp.tool()
def get_work_order(work_order_id: str) -> dict:
    """Read a work order from CMMS by ID."""

    init_db()
    work_order = get_by_work_order_id(work_order_id)
    if not work_order:
        return {"error": f"work order {work_order_id} not found"}
    return work_order


if __name__ == "__main__":
    transport = os.getenv("MCP_TRANSPORT", "stdio")
    mcp.run(transport=transport)  # type: ignore[arg-type]
